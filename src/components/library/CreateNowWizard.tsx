export type WizardResult = {
  title: string;
  subjectName: string;
  description: string;
  /** Comma-separated musical styles only — the voice is kept separate. */
  style: string;
  language: string;
  /** Selected artist voice label, including the multi-singer "Mix voice" option. */
  vocal: string;
  /** Vocals-only mode — no instrumental bed generated by the model. */
  vocalsOnly: boolean;
  /** Storage path of an uploaded beat the vocals should sing over ("" = none). */
  beatPath: string;
  /** Requested track length in minutes (3 minute floor). */
  targetMinutes: number;
  /** Whether the finished track should appear in the global player. */
  isPublic: boolean;
  /** Exact per-track lyric rating selected in this wizard run. */
  foulMouth: boolean;
  foulIntensity: number;
  /** AI-suggested title still resolving in the background (blank-title runs). */
  titlePromise?: Promise<string>;
};

/** Raw wizard inputs — kept by the parent so a retry never loses them. */
export type WizardDraft = {
  title: string;
  subjectName: string;
  description: string;
  styles: string[];
  gender: string;
  languages: string[];
  vocalsOnly: boolean;
  beatPath: string;
  beatName: string;
  targetMinutes: number;
  isPublic: boolean;
};


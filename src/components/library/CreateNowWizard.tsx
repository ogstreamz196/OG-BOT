export function CreateNowWizard({
  open,
  onOpenChange,
  onComplete,
  initialDraft,
  submitLabel = "Create my song",
  guestMode = false,
}: {
  open: boolean;
  onOpenChange: (v: boolean) => void;
  onComplete: (result: WizardResult, draft: WizardDraft) => void;
  initialDraft?: WizardDraft;
  submitLabel?: string;
  /** Signed-out preview: nothing is saved or generated; all styles browsable. */
  guestMode?: boolean;
}) {
  const [step, setStep] = useState(1);
  const { isVip: roleVip } = useRole();
  // New accounts start with 15 days of VIP, so guests can pick any style.
  const isVip = guestMode || roleVip;
  const navigateVip = useNavigate();
  const [title, setTitle] = useState("");
  const [subjectName, setSubjectName] = useState("");
  const [description, setDescription] = useState("");
  const [styles, setStyles] = useState<string[]>([]);
  const [gender, setGender] = useState("Mix voice");
  const [languages, setLanguages] = useState<string[]>([]);
  const [vocalsOnly, setVocalsOnly] = useState(false);
  const [targetMinutes, setTargetMinutes] = useState(3);
  const [isPublic, setIsPublic] = useState(true);
  const { foulMouth: savedFoulMouth } = useFoulMouth();
  const setFoulMouth = useSetFoulMouth();
  const ratingSaving = !guestMode && setFoulMouth.isPending;
  const { intensity: savedIntensity } = useFoulIntensity();
  const setFoulIntensity = useSetFoulIntensity();
  const [intensityLocal, setIntensityLocal] = useState<number | null>(null);
  const intensity = intensityLocal ?? (guestMode ? 0 : savedIntensity);
  const foulMouth = guestMode ? intensity > 0 : savedFoulMouth;
  const isNasheed = styles.includes("Nasheed");
  const [beatPath, setBeatPath] = useState("");
  const [beatName, setBeatName] = useState("");
  const [uploadingBeat, setUploadingBeat] = useState(false);
  const [confirmClose, setConfirmClose] = useState(false);

  const wizardScrollRef = useRef<HTMLDivElement | null>(null);
  const [naming, setNaming] = useState(false);
  const [showAllStyles, setShowAllStyles] = useState(false);
  const [showAllLanguages, setShowAllLanguages] = useState(false);
  const explicit = !isNasheed && intensity > 0;
  const suggestTitle = useServerFn(suggestTrackTitle);

  const toggle = (list: string[], v: string) =>
    list.includes(v) ? list.filter((x) => x !== v) : [...list, v];

  const selectRating = (explicit: boolean) => {
    const nextIntensity = explicit ? 3 : 0;
    setIntensityLocal(nextIntensity);
    if (guestMode) return;
    setFoulIntensity.mutate(nextIntensity);
    setFoulMouth.mutate(explicit);
  };

  const changeIntensity = (next: number) => {
    const value = Math.max(0, Math.min(3, Math.round(next)));
    setIntensityLocal(value);
    if (guestMode) return;
    if (value > 0 !== foulMouth) setFoulMouth.mutate(value > 0);
  };

  const saveIntensity = (next: number) => {
    if (guestMode) return;
    setFoulIntensity.mutate(Math.max(0, Math.min(3, Math.round(next))));
  };

  // Reopen with whatever the user last entered so a retry keeps their work.
  useEffect(() => {
    if (!open) return;
    setStep(1);
    setConfirmClose(false);
    const d = initialDraft;
    if (!d) return;
    setTitle(d.title);
    setSubjectName(d.subjectName);
    setDescription(d.description);
    setStyles(d.styles);
    setGender(d.gender && d.gender !== "Any voice" ? d.gender : "Mix voice");
    setLanguages(d.languages);
    setVocalsOnly(d.vocalsOnly ?? false);
    setBeatPath(d.beatPath ?? "");
    setBeatName(d.beatName ?? "");
    setTargetMinutes(d.targetMinutes || 3);
    setIsPublic(d.isPublic ?? true);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open]);

  // Each stage starts at the top. On phones the dialog itself is the single
  // page scroller; desktop keeps the compact inner-panel behaviour.
  useEffect(() => {
    if (!open) return;
    wizardScrollRef.current?.scrollTo({ top: 0, behavior: "smooth" });
  }, [open, step]);

  const dirty =
    title.trim().length > 0 ||
    subjectName.trim().length > 0 ||
    description.trim().length > 0 ||
    styles.length > 0 ||
    languages.length > 0 ||
    gender.length > 0;

  /** Guard closing mid-step: confirm first, unless nothing was entered. */
  function requestClose() {
    if (dirty || step > 1) {
      setConfirmClose(true);
      return;
    }
    onOpenChange(false);
  }

  function discardAndClose() {
    setConfirmClose(false);
    setTitle("");
    setSubjectName("");
    setDescription("");
    setStyles([]);
    setGender("Mix voice");
    setLanguages([]);
    setVocalsOnly(false);
    setBeatPath("");
    setBeatName("");
    setTargetMinutes(3);
    setIsPublic(true);
    setStep(1);
    onOpenChange(false);
  }

  const stepValid = useMemo(() => {
    switch (step) {
      case 1:
        // Title is optional — left blank, OG Bot names the track for you.
        return subjectName.trim().length > 0 && description.trim().length >= 12;
      case 2:
        return styles.length > 0;
      case 3:
        // Beat upload is always optional — skipping gives a pure a cappella.
        return !uploadingBeat;
      default:
        // English is always included in the remix, so selecting English alone
        // (no additional languages) is a valid choice.
        return true;
    }
  }, [step, subjectName, description, styles, languages, uploadingBeat]);

  const hint = useMemo(() => {
    if (stepValid) return null;
    switch (step) {
      case 1:
        if (!subjectName.trim()) return "Add who it's about to continue.";
        return "Add a few more words about the story or vibe.";
      case 2:
        return "Pick at least one style (you can stack a few).";
      case 3:
        return "Hang on — your beat is still uploading.";
      default:
        return "Pick a language, or continue for English.";
    }
  }, [step, stepValid, subjectName]);

  async function next() {
    if (!stepValid || naming) return;
    if (step < TOTAL_STEPS) {
      setStep((s) => s + 1);
      return;
    }
    await finish();
  }

  async function finish() {
    if (naming) return;

    // Blank title? Close instantly with a safe default and let the AI name it
    // in the background — the song only needs its title after lyrics finish.
    const typedTitle = title.trim();
    const fallbackTitle = localFallbackTitle(subjectName, description);
    const finalTitle = typedTitle || fallbackTitle;
    const titlePromise: Promise<string> | undefined = typedTitle || guestMode
      ? undefined
      : suggestTitle({
          data: {
            subjectName: subjectName.trim(),
            description: description.trim(),
            style: styles.filter(Boolean).join(", "),
          },
        })
          .then((res) => (res?.title ?? "").trim() || fallbackTitle)
          .catch(() => fallbackTitle);

    onComplete(
      {
        title: finalTitle,
        titlePromise,
        subjectName: subjectName.trim(),
        description: description.trim(),
        style: styles.filter(Boolean).join(", "),
        language: (languages.length ? Array.from(new Set(languages)) : ["English"]).join(" + "),
        vocal: gender,
        vocalsOnly: isNasheed || vocalsOnly,
        beatPath: isNasheed ? "" : vocalsOnly ? beatPath : "",
        targetMinutes,
        isPublic,
        foulMouth: !isNasheed && intensity > 0,
        foulIntensity: isNasheed ? 0 : intensity,
      },
      {
        title: finalTitle,
        subjectName,
        description,
        styles,
        gender,
        languages,
        vocalsOnly: isNasheed || vocalsOnly,
        beatPath: isNasheed ? "" : beatPath,
        beatName: isNasheed ? "" : beatName,
        targetMinutes,
        isPublic,
      },
    );
    onOpenChange(false);
  }

  async function uploadBeat(file: File) {
    if (!file.type.startsWith("audio/")) {
      toast.error("Please choose an audio file (MP3, WAV, M4A…)");
      return;
    }
    if (file.size > 20 * 1024 * 1024) {
      toast.error("Beat must be under 20MB");
      return;
    }
    setUploadingBeat(true);
    try {
      const { data: auth } = await supabase.auth.getUser();
      const uid = auth.user?.id;
      if (!uid) throw new Error("You need to be signed in to upload a beat");
      const ext = file.name.split(".").pop()?.toLowerCase() || "mp3";
      const path = `${uid}/${crypto.randomUUID()}.${ext}`;
      const { error } = await supabase.storage
        .from("beats")
        .upload(path, file, { contentType: file.type, upsert: false });
      if (error) throw error;
      setBeatPath(path);
      setBeatName(file.name);
      toast.success("Beat uploaded — vocals will ride on it");
    } catch (e) {
      toast.error(e instanceof Error ? e.message : "Couldn't upload that beat");
    } finally {
      setUploadingBeat(false);
    }
  }

  const lengthControl = (
    <div className="space-y-2">
      <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
        Length of track
      </p>
      <div className="flex items-center gap-3 rounded-lg border border-border bg-card/40 p-2">
        <button
          type="button"
          aria-label="Shorter track"
          disabled={targetMinutes <= MIN_LENGTH}
          onClick={() => setTargetMinutes((m) => Math.max(MIN_LENGTH, m - 1))}
          className="grid h-10 w-10 shrink-0 place-items-center rounded-lg border border-border bg-background text-lg font-bold transition hover:border-primary/50 disabled:opacity-40"
        >
          −
        </button>
        <div className="min-w-0 flex-1 text-center">
          <p className="text-xl font-bold tabular-nums leading-none">{targetMinutes} min</p>
          <p className="mt-1 text-xs font-medium text-muted-foreground">
            {targetMinutes > MIN_LENGTH
              ? `+${targetMinutes - MIN_LENGTH} coin${targetMinutes - MIN_LENGTH === 1 ? "" : "s"}`
              : "Included"}
          </p>
        </div>
        <button
          type="button"
          aria-label="Longer track (1 extra coin)"
          disabled={targetMinutes >= MAX_LENGTH}
          onClick={() => setTargetMinutes((m) => Math.min(MAX_LENGTH, m + 1))}
          className="grid h-10 w-10 shrink-0 place-items-center rounded-lg border border-primary/40 bg-primary/15 text-lg font-bold text-primary transition hover:bg-primary/25 disabled:opacity-40"
        >
          +
        </button>
      </div>
      <p className="text-xs text-muted-foreground">
        Every length is free to create. Pay only when you download the full track.
      </p>
    </div>
  );

  return (
    <Dialog open={open} onOpenChange={(v) => (v ? onOpenChange(true) : requestClose())}>
      <DialogContent
        ref={wizardScrollRef}
        onEscapeKeyDown={(e) => {
          e.preventDefault();
          requestClose();
        }}
        className="block h-[calc(100dvh-env(safe-area-inset-top)-env(safe-area-inset-bottom))] w-full max-w-none overflow-y-auto overscroll-y-contain rounded-none border-x-0 border-white/10 bg-card/95 px-4 pb-[max(0.75rem,env(safe-area-inset-bottom))] pt-4 backdrop-blur-2xl shadow-2xl sm:flex sm:h-auto sm:max-h-[calc(100dvh-2rem)] sm:w-[calc(100vw-1.5rem)] sm:max-w-lg sm:flex-col sm:gap-3 sm:overflow-hidden sm:rounded-2xl sm:border-x sm:px-6 sm:py-6"
      >
        <DialogHeader className="shrink-0 space-y-2 pb-3 text-left sm:pb-0">
          <div className="flex items-center justify-between gap-3 pr-8">
            <span className="inline-flex items-center gap-1.5 rounded-full border border-primary/40 bg-primary/15 px-2.5 py-1 text-[0.7rem] font-black uppercase tracking-[0.2em] text-primary">
              <Sparkles className="h-3 w-3" />
              Create now
            </span>
            <span className="text-xs font-bold uppercase tracking-[0.16em] text-muted-foreground">
              Step {step} of {TOTAL_STEPS}
            </span>
          </div>
          <div
            className="h-1.5 w-full overflow-hidden rounded-full bg-white/10"
            role="progressbar"
            aria-valuemin={1}
            aria-valuemax={TOTAL_STEPS}
            aria-valuenow={step}
            aria-label="Wizard progress"
          >
            <div
              className="h-full bg-gradient-brand transition-all duration-300"
              style={{ width: `${(step / TOTAL_STEPS) * 100}%` }}
            />
          </div>
          <DialogTitle className="font-display text-2xl font-black leading-tight sm:text-3xl">
            {step === 1 && "Who's it for?"}
            {step === 2 && "Pick the sound"}
            {step === 3 && "Final touches"}
          </DialogTitle>
          <DialogDescription className="text-sm">
            {step === 1 && "A name and a little story is all OG Bot needs."}
            {step === 2 && "Mix styles if you like, then choose who sings."}
            {step === 3 && "Language, length and rating — then create."}
          </DialogDescription>
        </DialogHeader>

        <div
          className="-mx-1 min-h-0 space-y-3 px-1 sm:flex-1 sm:overflow-y-auto sm:overscroll-contain"
          style={{ WebkitOverflowScrolling: "touch", touchAction: "pan-y" }}
        >
          <div
            key={step}
            className="min-h-[168px] animate-in fade-in slide-in-from-right-4 py-1 duration-300"
          >
            {step === 1 && (
              <div className="space-y-5">
                <div role="group" aria-label="Track mode" className="grid grid-cols-2 gap-2">
                  {(() => {
                    const dissPicks = ["UK Drill", "Grime", "Trap"];
                    const dissOn = styles.some((s) => dissPicks.includes(s)) && explicit;
                    return (
                      <>
                        <button
                          type="button"
                          aria-pressed={dissOn}
                          onClick={() => {
                            const pick =
                              dissPicks.find((s) => isVip || isFreeStyle(s)) ?? dissPicks[2];
                            setStyles([pick]);
                            selectRating(true);
                            if (!description.trim())
                              setDescription("What did they do? Give OG Bot the ammo: ");
                          }}
                          className={cn(
                            "rounded-xl border-2 px-3 py-2.5 text-sm font-black uppercase tracking-wide transition",
                            dissOn
                              ? "border-destructive bg-destructive text-destructive-foreground"
                              : "border-destructive/50 bg-destructive/10 text-foreground hover:bg-destructive/20",
                          )}
                        >
                          🔥 Diss track
                        </button>
                        <button
                          type="button"
                          aria-pressed={!dissOn}
                          onClick={() => {
                            if (dissOn) setStyles([]);
                          }}
                          className={cn(
                            "rounded-xl border-2 px-3 py-2.5 text-sm font-black uppercase tracking-wide transition",
                            !dissOn
                              ? "border-primary bg-primary/15 text-foreground"
                              : "border-border bg-background/40 text-muted-foreground",
                          )}
                        >
                          🎵 Custom song
                        </button>
                      </>
                    );
                  })()}
                </div>
                <div className="space-y-3 rounded-xl border border-border bg-background/40 p-3">
                  <Label
                    htmlFor="wiz-subject"
                    className="text-xs font-semibold uppercase tracking-wider text-muted-foreground"
                  >
                    Their name
                  </Label>
                  <Input
                    id="wiz-subject"
                    autoFocus
                    value={subjectName}
                    maxLength={60}
                    onChange={(e) => setSubjectName(e.target.value)}
                    onKeyDown={(e) => e.key === "Enter" && next()}
                    placeholder="e.g. Aaliyah, the crew, or yourself"
                    className="h-11 rounded-lg border border-border bg-background text-base font-semibold"
                  />
                </div>

                <div className="space-y-3 rounded-xl border border-border bg-background/40 p-3">
                  <Label
                    htmlFor="wiz-desc"
                    className="text-xs font-semibold uppercase tracking-wider text-muted-foreground"
                  >
                    The story
                  </Label>
                  <Textarea
                    id="wiz-desc"
                    rows={4}
                    value={description}
                    maxLength={2000}
                    onChange={(e) => setDescription(e.target.value)}
                    placeholder="Vibes, memories, inside jokes, the moment you want in the lyrics…"
                    className="min-h-[110px] resize-y rounded-lg border border-border bg-background text-sm leading-relaxed"
                  />
                  <p className="text-xs tabular-nums text-muted-foreground">
                    {description.trim().length}/2000
                  </p>
                </div>
              </div>
            )}

            {step === 2 && (
              <div className="space-y-4">
                <div
                  role="group"
                  aria-label="Track styles"
                  className="grid grid-cols-2 gap-2 sm:grid-cols-3"
                >
                  {(showAllStyles
                    ? STYLES
                    : STYLES.filter((x, i) => i < 12 || styles.includes(x))
                  ).map((s) => {
                    const selected = styles.includes(s);
                    const locked = !isVip && !isFreeStyle(s) && !selected;
                    return (
                      <button
                        key={s}
                        type="button"
                        aria-pressed={selected}
                        onClick={() => {
                          if (locked) {
                            toast(`👑 ${s} is an OG VIP style`, {
                              description: "Unlock all 50+ styles & moods, plus custom style and language requests.",
                              action: { label: "Get VIP", onClick: () => void navigateVip({ to: "/buy-coins" }) },
                            });
                            return;
                          }
                          if (s === "Nasheed") {
                            setStyles(selected ? [] : ["Nasheed"]);
                            setVocalsOnly(!selected);
                            setBeatPath("");
                            setBeatName("");
                            if (!selected) selectRating(false);
                            return;
                          }
                          setStyles((prev) =>
                            toggle(
                              prev.filter((style) => style !== "Nasheed"),
                              s,
                            ),
                          );
                        }}
                        className={cn(
                          "min-h-11 rounded-xl border px-3 py-2.5 text-sm font-bold transition focus:outline-none focus-visible:ring-2 focus-visible:ring-primary",
                          selected
                            ? "border-primary bg-primary/20 text-foreground shadow-glow"
                            : locked
                              ? "border-coin/30 bg-coin/5 text-muted-foreground/70"
                              : "border-white/10 bg-card/60 text-muted-foreground hover:border-primary/40 hover:text-foreground",
                        )}
                      >
                        {locked && (
                          <span aria-label="VIP only" className="mr-1 inline-flex items-end text-xs">
                            <span className="relative">🔒<span className="absolute -top-2 left-0.5 text-[0.7rem]">👑</span></span>
                          </span>
                        )}
                        {s}
                      </button>
                    );
                  })}
                </div>
                <button
                  type="button"
                  onClick={() => setShowAllStyles((v) => !v)}
                  aria-expanded={showAllStyles}
                  className="flex min-h-12 w-full items-center justify-center gap-2 rounded-xl border-2 border-dashed border-primary/50 bg-primary/10 px-4 text-sm font-black uppercase tracking-wide text-primary transition hover:border-primary hover:bg-primary/20 focus:outline-none focus-visible:ring-2 focus-visible:ring-primary"
                >
                  {showAllStyles ? (
                    <>
                      <ChevronUp className="h-4 w-4" />
                      Show fewer styles
                    </>
                  ) : (
                    <>
                      <Music4 className="h-4 w-4" />
                      More styles
                      <span className="rounded-full bg-primary/25 px-2 py-0.5 text-xs font-black tabular-nums">
                        +{STYLES.length - 12}
                      </span>
                      <ChevronDown className="h-4 w-4" />
                    </>
                  )}
                </button>

                <div>
                  <p className="mb-2 text-xs font-black uppercase tracking-[0.18em] text-muted-foreground">
                    Artist voice
                  </p>
                  <div
                    role="group"
                    aria-label="Artist voice"
                    className="grid grid-cols-2 gap-2 sm:grid-cols-4"
                  >
                    {GENDERS.map((g) => {
                      const selected = gender === g;
                      return (
                        <button
                          key={g}
                          type="button"
                          aria-pressed={selected}
                          onClick={() => setGender(g)}
                          className={cn(
                            "min-h-11 rounded-xl border px-3 py-2 text-xs font-bold transition focus:outline-none focus-visible:ring-2 focus-visible:ring-primary",
                            selected
                              ? "border-primary bg-primary/20 text-foreground shadow-glow"
                              : "border-white/10 bg-card/60 text-muted-foreground hover:border-primary/40 hover:text-foreground",
                          )}
                        >
                          {g}
                        </button>
                      );
                    })}
                  </div>
                </div>
              </div>
            )}

            {step === 3 && (
              <div className="space-y-5">
                {/* Content rating — replaces the old foul mouth toggle. */}
                <div className="space-y-2">
                  <p className="text-xs font-black uppercase tracking-[0.18em] text-muted-foreground">
                    Lyrics rating
                  </p>
                  <div role="group" aria-label="Lyrics rating" className="grid grid-cols-2 gap-2">
                    <button
                      type="button"
                      aria-pressed={!foulMouth}
                      disabled={ratingSaving}
                      onClick={() => selectRating(false)}
                      className={cn(
                        "flex flex-col items-center gap-1.5 rounded-xl border px-3 py-3 transition focus:outline-none focus-visible:ring-2 focus-visible:ring-primary disabled:opacity-60",
                        !foulMouth
                          ? "border-emerald-400 bg-emerald-400/15"
                          : "border-border bg-background hover:border-emerald-400/40",
                      )}
                    >
                      <img
                        src={ratingPgImg}
                        alt="PG — Parental Guidance rating certificate"
                        loading="lazy"
                        width={56}
                        height={56}
                        className={cn(
                          "h-14 w-14 object-contain transition",
                          !foulMouth ? "opacity-100" : "opacity-50 saturate-50",
                        )}
                      />
                      <span className="text-sm font-bold">PG rated</span>
                      <span className="text-xs text-muted-foreground">Clean, family safe</span>
                    </button>
                    <button
                      type="button"
                      aria-pressed={foulMouth}
                      disabled={ratingSaving || isNasheed}
                      onClick={() => selectRating(true)}
                      className={cn(
                        "flex flex-col items-center gap-1.5 rounded-xl border px-3 py-3 transition focus:outline-none focus-visible:ring-2 focus-visible:ring-primary disabled:opacity-60",
                        foulMouth
                          ? "border-destructive bg-destructive/20"
                          : "border-border bg-background hover:border-destructive/40",
                      )}
                    >
                      <img
                        src={rating18Img}
                        alt="18 — adults only rating certificate"
                        loading="lazy"
                        width={56}
                        height={56}
                        className={cn(
                          "h-14 w-14 object-contain transition",
                          foulMouth ? "opacity-100" : "opacity-50 saturate-50",
                        )}
                      />
                      <span className="text-sm font-bold">18+ rated</span>
                      <span className="text-xs text-muted-foreground">Explicit, no filter</span>
                    </button>
                  </div>

                  {!isNasheed && foulMouth && (
                    <div className="space-y-2 rounded-xl border border-destructive/30 bg-destructive/5 px-3 py-3">
                      <div className="flex items-baseline justify-between gap-2">
                        <label
                          htmlFor="foul-intensity"
                          className="text-xs font-black uppercase tracking-[0.18em] text-muted-foreground"
                        >
                          Swearing intensity
                        </label>
                        <span className="text-xs font-bold text-destructive">
                          {INTENSITY_LABELS[intensity]}
                        </span>
                      </div>
                      <Slider
                        id="foul-intensity"
                        aria-label="Swearing intensity"
                        min={0}
                        max={3}
                        step={1}
                        value={[intensity]}
                        onValueChange={(v) => changeIntensity(v[0] ?? 3)}
                        onValueCommit={(v) => saveIntensity(v[0] ?? 3)}
                      />
                      <div className="flex justify-between text-[0.7rem] text-muted-foreground">
                        <span>Clean</span>
                        <span>Mild</span>
                        <span>Strong</span>
                        <span>Savage</span>
                      </div>
                    </div>
                  )}
                </div>

                <div className="space-y-2">
                  <div className="flex items-baseline justify-between gap-2">
                    <p className="text-xs font-black uppercase tracking-[0.18em] text-muted-foreground">
                      Language
                    </p>
                    <p className="text-xs font-semibold text-muted-foreground">
                      {languages.length ? `${languages.length} selected` : "English by default"}
                    </p>
                  </div>
                  <div
                    role="group"
                    aria-label="Languages"
                    style={{ WebkitOverflowScrolling: "touch", touchAction: "pan-y" }}
                    className="grid grid-cols-2 gap-2 rounded-xl border border-border bg-background/40 p-2 sm:grid-cols-3"
                  >
                    {(showAllLanguages
                      ? POOLS.language
                      : POOLS.language.filter((x, i) => i < 8 || languages.includes(x))
                    ).map((l) => {
                      const selected = languages.includes(l);
                      return (
                        <button
                          key={l}
                          type="button"
                          aria-pressed={selected}
                          onClick={() => setLanguages((prev) => toggle(prev, l))}
                          className={cn(
                            "min-h-10 rounded-lg border px-3 py-2 text-sm font-semibold transition focus:outline-none focus-visible:ring-2 focus-visible:ring-primary",
                            selected
                              ? "border-primary bg-primary/20 text-foreground"
                              : "border-border bg-card/60 text-muted-foreground hover:border-primary/40 hover:text-foreground",
                          )}
                        >
                          {l}
                        </button>
                      );
                    })}
                  </div>
                  {POOLS.language.length > 8 && (
                    <button
                      type="button"
                      onClick={() => setShowAllLanguages((v) => !v)}
                      aria-expanded={showAllLanguages}
                      className="flex min-h-12 w-full items-center justify-center gap-2 rounded-xl border-2 border-dashed border-primary/50 bg-primary/10 px-4 text-sm font-black uppercase tracking-wide text-primary transition hover:border-primary hover:bg-primary/20 focus:outline-none focus-visible:ring-2 focus-visible:ring-primary"
                    >
                      {showAllLanguages ? (
                        <>
                          <ChevronUp className="h-4 w-4" />
                          Show fewer languages
                        </>
                      ) : (
                        <>
                          <Globe2 className="h-4 w-4" />
                          More languages
                          <span className="rounded-full bg-primary/25 px-2 py-0.5 text-xs font-black tabular-nums">
                            +{POOLS.language.length - 8}
                          </span>
                          <ChevronDown className="h-4 w-4" />
                        </>
                      )}
                    </button>
                  )}
                </div>

                {lengthControl}

                {/* Voice setup: vocals-only and, when on, the beat it rides. */}
                <div className="space-y-2">
                  <p className="text-xs font-black uppercase tracking-[0.18em] text-muted-foreground">
                    Voice setup
                  </p>
                  <button
                    type="button"
                    aria-pressed={vocalsOnly}
                    onClick={() => {
                      if (!isNasheed) setVocalsOnly((v) => !v);
                    }}
                    className={cn(
                      "flex w-full items-center gap-3 rounded-xl border px-4 py-3 text-left transition focus:outline-none focus-visible:ring-2 focus-visible:ring-primary",
                      vocalsOnly
                        ? "border-primary bg-primary/15"
                        : "border-border bg-background hover:border-primary/40",
                    )}
                  >
                    <Mic2
                      className={cn(
                        "h-5 w-5 shrink-0",
                        vocalsOnly ? "text-primary" : "text-muted-foreground",
                      )}
                    />
                    <span className="min-w-0 flex-1">
                      <span className="block text-sm font-bold">Vocals only</span>
                      <span className="block text-xs text-muted-foreground">
                        Strips every instrument — pure voice, humming at most.
                      </span>
                    </span>
                    <span
                      className={cn(
                        "shrink-0 rounded-full px-2.5 py-1 text-[0.7rem] font-black uppercase tracking-wider",
                        vocalsOnly
                          ? "bg-primary text-primary-foreground"
                          : "bg-muted text-muted-foreground",
                      )}
                    >
                      {isNasheed ? "Required" : vocalsOnly ? "On" : "Off"}
                    </span>
                  </button>

                  {isNasheed && (
                    <p className="rounded-xl border border-emerald-400/30 bg-emerald-400/10 px-3 py-2 text-xs font-medium text-emerald-300">
                      Nasheed is always clean and voice-only: no instruments, beats, or foul
                      language.
                    </p>
                  )}

                  {vocalsOnly && (
                    <div className="space-y-3 rounded-xl border border-border bg-background/60 p-4">
                      <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
                        Upload a beat (optional)
                      </p>
                      <p className="text-xs leading-relaxed text-muted-foreground">
                        Add an MP3 or WAV and the vocals are performed over it. Skip it and you get
                        a pure a cappella — voice and humming only, no instruments at all.
                      </p>
                      <input
                        id="wiz-beat"
                        type="file"
                        accept="audio/*"
                        disabled={uploadingBeat}
                        onChange={(e) => {
                          const file = e.target.files?.[0];
                          e.target.value = "";
                          if (file) void uploadBeat(file);
                        }}
                        className="block w-full text-xs file:mr-3 file:min-h-10 file:rounded-lg file:border-0 file:bg-primary/20 file:px-4 file:py-2 file:text-xs file:font-bold file:uppercase file:tracking-wide file:text-primary"
                      />
                      {uploadingBeat && (
                        <p className="text-xs font-semibold text-primary" aria-live="polite">
                          Uploading beat…
                        </p>
                      )}
                      {beatPath && !uploadingBeat && (
                        <div className="flex items-center gap-2 text-xs font-semibold text-foreground">
                          <Music4 className="h-4 w-4 text-primary" />
                          <span className="min-w-0 flex-1 truncate">{beatName}</span>
                          <Button
                            type="button"
                            size="sm"
                            variant="ghost"
                            className="h-8 text-muted-foreground hover:text-destructive"
                            onClick={() => {
                              setBeatPath("");
                              setBeatName("");
                            }}
                          >
                            Remove
                          </Button>
                        </div>
                      )}
                    </div>
                  )}
                </div>


                {/* Compact track recipe so nothing is a surprise before creating. */}
                <div className="rounded-xl border border-border bg-background/60 p-3">
                  <div className="flex items-center justify-between gap-2">
                    <p className="min-w-0 truncate text-sm font-bold text-foreground">
                      {title.trim() ||
                        `For ${subjectName.trim().slice(0, 24) || "you"} · OG Bot names it`}
                    </p>
                    <span className="flex shrink-0 items-center gap-1 text-xs font-semibold text-muted-foreground">
                      {isPublic ? (
                        <Globe2 className="h-3.5 w-3.5 text-primary" />
                      ) : (
                        <Lock className="h-3.5 w-3.5 text-primary" />
                      )}
                      {isPublic ? "Global" : "Private"}
                    </span>
                  </div>
                  <div className="mt-2 flex flex-wrap gap-1.5">
                    {[
                      styles.join(", ") || "No style",
                      `${targetMinutes} min`,
                      (languages.length ? languages : ["English"]).join(", "),
                      gender || "Mix voice",
                      isNasheed
                        ? "Nasheed, voice-only"
                        : vocalsOnly
                          ? beatPath
                            ? "Vocals over your beat"
                            : "A cappella"
                          : "Full production",
                      isNasheed
                        ? "Strictly clean"
                        : explicit
                          ? `18+ · ${INTENSITY_LABELS[intensity]}`
                          : "PG",
                    ].map((chip) => (
                      <span
                        key={chip}
                        className="rounded-full border border-white/10 bg-card/60 px-2.5 py-1 text-xs font-semibold text-muted-foreground"
                      >
                        {chip}
                      </span>
                    ))}
                  </div>
                </div>
              </div>
            )}
          </div>

          {hint && (
            <p className="text-xs font-medium text-muted-foreground" aria-live="polite">
              {hint}
            </p>
          )}
        </div>

        <div className="-mx-4 mt-6 shrink-0 border-t border-white/10 px-4 pb-[max(0.75rem,env(safe-area-inset-bottom))] pt-4 sm:-mx-6 sm:mt-1 sm:px-6 sm:pb-1">
          <div className="flex items-center gap-2">
            <Button
              type="button"
              variant="ghost"
              disabled={step === 1}
              onClick={() => setStep((s) => Math.max(1, s - 1))}
              className="min-h-11 shrink-0 gap-1.5 px-2.5 sm:px-4"
              aria-label="Back"
            >
              <ArrowLeft className="h-4 w-4" />
              <span className="hidden sm:inline">Back</span>
            </Button>
            <Button
              type="button"
              variant="ghost"
              onClick={requestClose}
              className="min-h-11 shrink-0 gap-1.5 px-2.5 text-muted-foreground hover:text-destructive sm:px-4"
              aria-label="Cancel"
            >
              <X className="h-4 w-4" />
              <span className="hidden sm:inline">Cancel</span>
            </Button>
            {step < TOTAL_STEPS && (
              <Button
                type="button"
                onClick={() => void next()}
                disabled={!stepValid || naming}
                className="ml-auto min-h-11 min-w-0 flex-1 gap-1.5 whitespace-nowrap bg-gradient-brand font-black uppercase tracking-wide text-primary-foreground shadow-glow sm:flex-none"
              >
                Next
                <ArrowRight className="h-4 w-4 shrink-0" />
              </Button>
            )}
          </div>

          {step === TOTAL_STEPS && (
            <div className="mt-2 grid grid-cols-[minmax(0,1fr)_7.25rem] gap-2">
              <Button
                type="button"
                onClick={() => void next()}
                disabled={!stepValid || naming}
                className="min-h-12 min-w-0 gap-2 bg-gradient-brand font-black uppercase tracking-wide text-primary-foreground shadow-glow"
              >
                <Check className="h-4 w-4 shrink-0" />
                <span className="truncate">{naming ? "Naming your track…" : submitLabel}</span>
              </Button>
              <Button
                type="button"
                variant="outline"
                aria-pressed={isPublic}
                aria-label={
                  isPublic
                    ? "Global player. Tap to make private"
                    : "Private library. Tap to make global"
                }
                onClick={() => setIsPublic((value) => !value)}
                className={cn(
                  "min-h-12 min-w-0 flex-col gap-0.5 px-2",
                  isPublic && "border-primary bg-primary/15 text-primary",
                )}
              >
                <span className="flex items-center gap-1.5 text-xs font-black uppercase">
                  {isPublic ? <Globe2 className="h-3.5 w-3.5" /> : <Lock className="h-3.5 w-3.5" />}
                  {isPublic ? "Global" : "Private"}
                </span>
                <span className="text-[0.7rem] font-semibold normal-case text-muted-foreground">
                  Tap to change
                </span>
              </Button>
            </div>
          )}
        </div>
      </DialogContent>

      <AlertDialog open={confirmClose} onOpenChange={setConfirmClose}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Close before finishing?</AlertDialogTitle>
            <AlertDialogDescription>
              You're on step {step} of {TOTAL_STEPS}. Keep your answers and come back later, or
              discard them and start fresh.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter className="gap-2">
            <AlertDialogCancel className="min-h-11">Keep editing</AlertDialogCancel>
            <Button
              type="button"
              variant="secondary"
              className="min-h-11"
              onClick={() => {
                setConfirmClose(false);
                onOpenChange(false);
              }}
            >
              Save &amp; close
            </Button>
            <AlertDialogAction
              onClick={discardAndClose}
              className="min-h-11 bg-destructive text-destructive-foreground hover:bg-destructive/90"
            >
              Discard
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>


    </Dialog>
  );
}

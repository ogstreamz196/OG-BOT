#!/usr/bin/env bash
# Builds supabase/hub/og_bot_init.sql: OG B0T's whole database structure as
# the og_bot schema for the OGSTREAMZ hub. Needs a local Postgres 16+
# (initdb, pg_ctl, psql, pg_dump). Touches no remote database.
#
#   1. replay every supabase/migrations file on a throwaway local Postgres
#      (with stand-ins for the hosted platform)
#   2. apply supabase/hub/01_drift_from_live.sql (live changes that never
#      reached the migrations)
#   3. apply supabase/hub/02_to_og_bot.sql (public → og_bot, hub rules)
#   4. dump og_bot, plus the auth.users triggers and realtime tables
#
# Newer pg_dump adds \restrict lines, which only psql understands: they're
# left out so the file also runs through SQL tools.
#
# Usage: scripts/hub/build-og-bot-init.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
BIN="${PG_BIN:-$(dirname "$(command -v pg_ctl || ls /usr/lib/postgresql/*/bin/pg_ctl | tail -1)")}"
WORK="$(mktemp -d)"
PORT="${PG_PORT:-54331}"
RUN=()
if [ "$(id -u)" = "0" ]; then
  # initdb refuses to run as root.
  chown postgres "$WORK"
  RUN=(su postgres -c)
fi
run() { if [ ${#RUN[@]} -gt 0 ]; then "${RUN[@]}" "$*"; else bash -c "$*"; fi; }
cleanup() { run "$BIN/pg_ctl -D $WORK/data -m immediate stop" >/dev/null 2>&1 || true; rm -rf "$WORK"; }
trap cleanup EXIT

run "$BIN/initdb -D $WORK/data -A trust -U postgres" >/dev/null
run "$BIN/pg_ctl -D $WORK/data -o '-p $PORT -k $WORK' -l $WORK/log start" >/dev/null
sleep 2
PSQL=("$BIN/psql" -h "$WORK" -p "$PORT" -U postgres -X -q)

"${PSQL[@]}" -d postgres -c "create database build" >/dev/null
"${PSQL[@]}" -d build -f "$ROOT/scripts/hub/local-platform-stubs.sql" >/dev/null 2>&1
"${PSQL[@]}" -d build -c 'alter database build set search_path = "$user", public, extensions' >/dev/null

# Replay. Some old migrations repeat a realtime add, use platform-only
# extensions or insert rows for real accounts: those parts are made harmless
# here (schema only). Statement errors are listed, not fatal: the drift file
# and the live comparison cover what the history got wrong.
errors=0
for f in "$ROOT"/supabase/migrations/*.sql; do
  python3 - "$f" > "$WORK/cur.sql" <<'PY'
import re, sys
s = open(sys.argv[1]).read()
s = re.sub(r'(?im)^\s*alter\s+publication\s+supabase_realtime\s+add\s+table\s+([^;]+);',
           lambda m: "do $pub$ begin alter publication supabase_realtime add table %s; exception when duplicate_object then null; end $pub$;" % m.group(1), s)
s = re.sub(r'(?im)^\s*create\s+extension\s+(if\s+not\s+exists\s+)?"?(pg_cron|pg_net|supabase_vault|pgsodium|pg_graphql|pg_stat_statements)"?[^;]*;', '-- (platform extension)', s)
s = re.sub(r'(?im)^\s*(grant|revoke)[^;]*\bschema\s+cron\b[^;]*;', '-- (cron grant)', s)
sys.stdout.write("set session_replication_role = replica;\n" + s)
PY
  out=$("${PSQL[@]}" -d build -f "$WORK/cur.sql" 2>&1 | grep ERROR || true)
  if [ -n "$out" ]; then
    errors=$((errors + 1))
    echo "replay: $(basename "$f"): $out" >&2
  fi
done
echo "replay done ($errors migration(s) with statement errors, expected: 3)" >&2

"${PSQL[@]}" -d build -v ON_ERROR_STOP=1 -1 -f "$ROOT/supabase/hub/01_drift_from_live.sql" >/dev/null 2>&1
"${PSQL[@]}" -d build -v ON_ERROR_STOP=1 -1 -f "$ROOT/supabase/hub/02_to_og_bot.sql" >/dev/null 2>&1

OUT="$ROOT/supabase/hub/og_bot_init.sql"
{
  echo "-- og_bot_init: OG B0T's database structure as the og_bot schema in the"
  echo "-- OGSTREAMZ hub. GENERATED by scripts/hub/build-og-bot-init.sh; don't edit."
  echo "-- Applied by .github/workflows/og-bot-hub.yml (action: apply). Undo with"
  echo "-- supabase/hub/og_bot_rollback.sql. Adds the og_bot schema, two triggers on"
  echo "-- auth.users that only act on OG B0T's own users, and realtime tables."
  echo "-- Changes nothing that belongs to another app."
  echo
  "$BIN/pg_dump" -h "$WORK" -p "$PORT" -U postgres -d build --schema-only -n og_bot \
    --no-owner --no-comments | grep -v '^--' | grep -v '^\\' | sed '/^$/N;/^\n$/D'
  echo
  echo "-- Triggers on the shared auth.users table (see 02_to_og_bot.sql)."
  "${PSQL[@]}" -d build -At -c "select pg_get_triggerdef(t.oid) || ';' from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'auth' and c.relname = 'users' and t.tgname like 'og_bot_%' order by t.tgname"
  echo
  echo "-- Realtime, for the same tables as on Lovable Cloud."
  "${PSQL[@]}" -d build -At -c "select 'ALTER PUBLICATION supabase_realtime ADD TABLE og_bot.' || quote_ident(tablename) || ';' from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'og_bot' order by tablename"
  echo
  echo "COMMENT ON SCHEMA og_bot IS 'OG B0T (ogbot.co.uk). Hub rules: see the comment on schema public.';"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)" >&2
